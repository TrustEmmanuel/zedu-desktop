/// The country name to show. A stored name is returned unchanged (matched
/// without case). A two-letter code such as `Za` becomes its country name.
/// Anything else, including an unknown code, is returned trimmed.
String countryDisplayName(String value) {
  final trimmed = value.trim();
  if (trimmed.isEmpty) return trimmed;

  for (final country in kCountries) {
    if (country.toLowerCase() == trimmed.toLowerCase()) return country;
  }

  if (trimmed.length == 2) {
    final name = _kCountryCodes[trimmed.toUpperCase()];
    if (name != null) return name;
  }

  return trimmed;
}
